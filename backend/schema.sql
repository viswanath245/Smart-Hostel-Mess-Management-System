CREATE DATABASE IF NOT EXISTS smart_hostel_mess CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE smart_hostel_mess;

CREATE TABLE IF NOT EXISTS `students` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` VARCHAR(100) NOT NULL UNIQUE,
  `name` VARCHAR(150) NOT NULL,
  `email` VARCHAR(255) NOT NULL UNIQUE,
  `password` VARCHAR(255) NOT NULL,
  `phone` VARCHAR(40) NULL,
  `hostelBlock` VARCHAR(80) NULL,
  `roomNo` VARCHAR(40) NULL,
  `healthGoal` VARCHAR(255) NULL,
  `rewardPoints` INT NOT NULL DEFAULT 0,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_students_studentId` (`studentId`),
  CONSTRAINT `fk_students_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `meals` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `mealName` VARCHAR(150) NOT NULL,
  `mealType` ENUM('Breakfast','Lunch','Dinner') NOT NULL,
  `mealDate` DATETIME NOT NULL,
  `calories` DECIMAL(10,2) NOT NULL DEFAULT 0,
  `nutritionInfo` TEXT NULL,
  `preparationStatus` ENUM('Planned','Preparing','Ready') NOT NULL DEFAULT 'Planned',
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `vendors` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `vendorId` VARCHAR(100) NOT NULL UNIQUE,
  `vendorName` VARCHAR(150) NOT NULL,
  `phone` VARCHAR(40) NULL,
  `address` VARCHAR(500) NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_vendors_vendorId` (`vendorId`),
  CONSTRAINT `fk_vendors_vendorId` FOREIGN KEY (`vendorId`) REFERENCES `vendors`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `admins` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `adminId` VARCHAR(100) NOT NULL UNIQUE,
  `name` VARCHAR(150) NOT NULL,
  `email` VARCHAR(255) NOT NULL UNIQUE,
  `password` VARCHAR(255) NOT NULL,
  `role` VARCHAR(80) NOT NULL DEFAULT 'Admin',
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `staff` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `staffId` VARCHAR(100) NOT NULL UNIQUE,
  `name` VARCHAR(150) NOT NULL,
  `email` VARCHAR(255) NOT NULL UNIQUE,
  `password` VARCHAR(255) NOT NULL,
  `role` VARCHAR(80) NOT NULL DEFAULT 'Mess Staff',
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `attendance` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` BIGINT UNSIGNED NOT NULL,
  `mealId` BIGINT UNSIGNED NOT NULL,
  `attendanceTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `status` ENUM('Present','Absent','Missed') NOT NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_attendance_studentId` (`studentId`),
  CONSTRAINT `fk_attendance_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`),
  INDEX `idx_attendance_mealId` (`mealId`),
  CONSTRAINT `fk_attendance_mealId` FOREIGN KEY (`mealId`) REFERENCES `meals`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `complaints` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` BIGINT UNSIGNED NOT NULL,
  `subject` VARCHAR(100) NOT NULL,
  `description` VARCHAR(300) NOT NULL,
  `status` ENUM('Pending','In Progress','Resolved') NOT NULL DEFAULT 'Pending',
  `complaintDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_complaints_studentId` (`studentId`),
  CONSTRAINT `fk_complaints_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `crowd_monitoring` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `mealId` BIGINT UNSIGNED NOT NULL,
  `date` DATETIME NOT NULL,
  `studentCount` INT UNSIGNED NOT NULL,
  `crowdLevel` ENUM('Low','Normal','High') NOT NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_crowd_monitoring_mealId` (`mealId`),
  CONSTRAINT `fk_crowd_monitoring_mealId` FOREIGN KEY (`mealId`) REFERENCES `meals`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `food_waste` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `mealId` BIGINT UNSIGNED NOT NULL,
  `date` DATETIME NOT NULL,
  `foodPrepared` DECIMAL(10,2) NOT NULL,
  `foodWasted` DECIMAL(10,2) NOT NULL,
  `wastePercentage` DECIMAL(6,2) NOT NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_food_waste_mealId` (`mealId`),
  CONSTRAINT `fk_food_waste_mealId` FOREIGN KEY (`mealId`) REFERENCES `meals`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `inventory` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `vendorId` BIGINT UNSIGNED NOT NULL,
  `itemName` VARCHAR(100) NOT NULL,
  `quantity` DECIMAL(10,2) NOT NULL,
  `reorderLevel` DECIMAL(10,2) NOT NULL,
  `lastUpdated` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_inventory_vendorId` (`vendorId`),
  CONSTRAINT `fk_inventory_vendorId` FOREIGN KEY (`vendorId`) REFERENCES `vendors`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `meal_bookings` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` BIGINT UNSIGNED NOT NULL,
  `mealId` BIGINT UNSIGNED NOT NULL,
  `bookingDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `status` ENUM('Booked','Cancelled','Completed','Missed') NOT NULL DEFAULT 'Booked',
  `additionalMeal` BOOLEAN NOT NULL DEFAULT FALSE,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_meal_bookings_studentId` (`studentId`),
  CONSTRAINT `fk_meal_bookings_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`),
  INDEX `idx_meal_bookings_mealId` (`mealId`),
  CONSTRAINT `fk_meal_bookings_mealId` FOREIGN KEY (`mealId`) REFERENCES `meals`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `menu` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `mealId` BIGINT UNSIGNED NOT NULL,
  `foodItem` VARCHAR(150) NOT NULL,
  `day` VARCHAR(40) NOT NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_menu_mealId` (`mealId`),
  CONSTRAINT `fk_menu_mealId` FOREIGN KEY (`mealId`) REFERENCES `meals`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `notifications` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` BIGINT UNSIGNED NOT NULL,
  `title` VARCHAR(100) NOT NULL,
  `message` VARCHAR(250) NOT NULL,
  `notificationDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `status` ENUM('Unread','Read') NOT NULL DEFAULT 'Unread',
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_notifications_studentId` (`studentId`),
  CONSTRAINT `fk_notifications_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `orders` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `vendorId` BIGINT UNSIGNED NOT NULL,
  `itemName` VARCHAR(100) NOT NULL,
  `quantity` INT UNSIGNED NOT NULL,
  `orderDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `status` ENUM('Pending','Ordered','Delivered','Cancelled') NOT NULL DEFAULT 'Pending',
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_orders_vendorId` (`vendorId`),
  CONSTRAINT `fk_orders_vendorId` FOREIGN KEY (`vendorId`) REFERENCES `vendors`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `reviews` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` BIGINT UNSIGNED NOT NULL,
  `mealId` BIGINT UNSIGNED NOT NULL,
  `rating` TINYINT UNSIGNED NOT NULL,
  `comment` VARCHAR(250) NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_reviews_studentId` (`studentId`),
  CONSTRAINT `fk_reviews_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`),
  INDEX `idx_reviews_mealId` (`mealId`),
  CONSTRAINT `fk_reviews_mealId` FOREIGN KEY (`mealId`) REFERENCES `meals`(`id`),
  CONSTRAINT `chk_reviews_rating` CHECK (`rating` BETWEEN 1 AND 5)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `rewards` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` BIGINT UNSIGNED NOT NULL,
  `pointsEarned` INT UNSIGNED NOT NULL,
  `reason` VARCHAR(150) NOT NULL,
  `rewardDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_rewards_studentId` (`studentId`),
  CONSTRAINT `fk_rewards_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `votes` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `studentId` BIGINT UNSIGNED NOT NULL,
  `foodItem` VARCHAR(150) NOT NULL,
  `voteDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_votes_studentId` (`studentId`),
  CONSTRAINT `fk_votes_studentId` FOREIGN KEY (`studentId`) REFERENCES `students`(`id`)
) ENGINE=InnoDB;
